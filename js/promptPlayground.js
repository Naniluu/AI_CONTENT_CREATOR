// ==========================================================================
// CREOVATE - AI PROMPT PLAYGROUND & LIVE STYLE SIMULATOR (DEMO PROTOTYPE)
// Test creator LoRAs with local simulation animation before commissioning
// ==========================================================================

const PromptPlayground = {
  currentModelId: 'sim-aura-couture',
  isGenerating: false,

  init() {
    this.render();
  },

  render() {
    const container = document.getElementById('promptPlaygroundContainer');
    if (!container) return;

    const currentModel = CREOVATE_DATA.simulatorModels.find(m => m.id === this.currentModelId) || CREOVATE_DATA.simulatorModels[0];

    container.innerHTML = `
      <div class="glass-panel" style="padding:var(--space-8); border:1px solid var(--border-glow); box-shadow:var(--shadow-glow-purple); border-radius:var(--radius-xl);">
        <div style="display:flex; align-items:center; justify-content:space-between; flex-wrap:wrap; gap:12px; margin-bottom:var(--space-6);">
          <div>
            <div style="display:flex; align-items:center; gap:8px; margin-bottom:4px; flex-wrap:wrap;">
              <span class="badge badge-match">Sample Style Explorer</span>
              <span class="badge badge-amber">Demo Prototype Feature</span>
            </div>
            <h2 style="font-size:1.6rem;">Explore Sample Creator Styles</h2>
            <p style="font-size:0.88rem; color:var(--text-secondary);">Choose a sample style and run a short interface animation. The prompt, weights, and preview are not sent to or generated by an AI model.</p>
          </div>

          <!-- Model Selector Pills -->
          <div style="display:flex; gap:8px; flex-wrap:wrap;">
            ${CREOVATE_DATA.simulatorModels.map(m => `
              <button class="filter-chip ${m.id === this.currentModelId ? 'active' : ''}" onclick="PromptPlayground.selectModel('${m.id}')">
                ${m.name}
              </button>
            `).join('')}
          </div>
        </div>

        <div style="display:grid; grid-template-columns:1fr 1fr; gap:var(--space-8);">
          <!-- Left: Controls & Prompt Input -->
          <div style="display:flex; flex-direction:column; gap:var(--space-4);">
            <div>
              <div style="display:flex; justify-content:space-between; margin-bottom:6px; flex-wrap:wrap;">
              <label class="form-label">Sample Checkpoint</label>
                <span style="font-family:var(--font-mono); font-size:0.75rem; color:var(--accent-cyan);">${currentModel.baseModel} • By ${currentModel.creator}</span>
              </div>
              <div style="background:var(--bg-input); padding:10px 14px; border-radius:var(--radius-md); border:1px solid var(--border-subtle); font-size:0.85rem; color:var(--text-primary); display:flex; align-items:center; justify-content:space-between;">
                <strong>${currentModel.name}</strong>
                <span class="badge badge-verified">Demo Checkpoint Loaded</span>
              </div>
            </div>

            <div>
              <label class="form-label">Prompt Recipe</label>
              <textarea id="playgroundPromptInput" class="form-textarea" style="min-height:110px;">${currentModel.defaultPrompt}</textarea>
            </div>

            <!-- Token Injector Pills -->
            <div>
              <span style="font-size:0.75rem; text-transform:uppercase; color:var(--text-muted); font-weight:700;">Add Style Trigger Tokens:</span>
              <div style="display:flex; gap:6px; flex-wrap:wrap; margin-top:6px;">
                ${currentModel.presetTags.map(tag => `
                  <button class="vibe-pill" style="font-size:0.75rem; padding:3px 10px;" onclick="PromptPlayground.injectTag('${tag}')">
                    + ${tag}
                  </button>
                `).join('')}
              </div>
            </div>

            <!-- Generation Parameters -->
            <div style="display:grid; grid-template-columns:1fr 1fr; gap:var(--space-4);">
              <div>
                <label class="form-label">CFG Scale: <span id="cfgVal" style="color:var(--accent-cyan)">4.5</span></label>
                <input type="range" id="cfgScaleInput" min="1.0" max="12.0" step="0.5" value="4.5" style="width:100%; accent-color:var(--accent-cyan);" oninput="document.getElementById('cfgVal').innerText = this.value" />
              </div>
              <div>
                <label class="form-label">KSampler Steps: <span id="stepsVal" style="color:var(--accent-purple)">32</span></label>
                <input type="range" id="samplerStepsInput" min="15" max="50" step="1" value="32" style="width:100%; accent-color:var(--accent-purple);" oninput="document.getElementById('stepsVal').innerText = this.value" />
              </div>
            </div>

            <div>
              <button class="btn btn-primary btn-lg" id="runSimulationBtn" onclick="PromptPlayground.runSimulation()" style="width:100%;">
                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><polygon points="13 2 3 14 12 14 11 22 21 10 12 10 13 2"/></svg>
                Simulate Generation (Demo Animation)
              </button>
              <div style="font-size:0.74rem; color:var(--text-muted); text-align:center; margin-top:6px;">
                *Local progress animation only. No diffusion or image generation is running.
              </div>
            </div>
          </div>

          <!-- Right: Interactive Viewport & Latent Progress -->
          <div style="display:flex; flex-direction:column; justify-content:space-between; gap:16px;">
            <div style="position:relative; aspect-ratio:16/9; background:#000; border-radius:var(--radius-lg); overflow:hidden; border:1px solid var(--border-medium); box-shadow:0 15px 35px rgba(0,0,0,0.6);" id="simulationViewport">
              <img id="simRenderImg" src="${currentModel.sampleOutput}" alt="Sample reference image — not generated from this prompt" style="width:100%; height:100%; object-fit:cover; transition:filter 0.5s ease;" />

              <!-- Progress Overlay (Hidden until run) -->
              <div id="simProgressOverlay" style="position:absolute; inset:0; background:rgba(8,9,14,0.85); backdrop-filter:blur(8px); display:none; flex-direction:column; align-items:center; justify-content:center; padding:20px; text-align:center;">
                <div style="font-size:2rem; margin-bottom:8px; animation:spin 1.2s infinite linear;">⚙️</div>
                <div style="font-size:1.1rem; font-weight:700; color:var(--text-primary); margin-bottom:4px;" id="simStepLabel">Starting demo animation...</div>
                <div style="font-size:0.8rem; font-family:var(--font-mono); color:var(--accent-cyan); margin-bottom:14px;" id="simDenoiseLabel">Demo animation progress: 0%</div>
                <div style="width:75%; height:6px; background:rgba(255,255,255,0.1); border-radius:var(--radius-full); overflow:hidden;">
                  <div id="simProgressBar" style="width:0%; height:100%; background:var(--grad-primary); transition:width 0.1s linear;"></div>
                </div>
              </div>

              <div style="position:absolute; bottom:10px; right:10px; background:rgba(0,0,0,0.8); backdrop-filter:blur(6px); padding:4px 10px; border-radius:var(--radius-sm); font-family:var(--font-mono); font-size:0.72rem; color:#A78BFA; border:1px solid rgba(255,255,255,0.1);">
                Sample style weight: 0.85
              </div>
            </div>
            <div id="simPreviewStatus" role="status" aria-live="polite" style="font-size:0.75rem; color:var(--text-muted);">
              Sample preview image. The prompt and sliders are demonstration controls only.
            </div>

            <!-- Commission Trigger -->
            <div style="background:var(--bg-tertiary); padding:14px; border-radius:var(--radius-md); display:flex; align-items:center; justify-content:space-between; border:1px solid var(--border-subtle); flex-wrap:wrap; gap:10px;">
              <div>
                <strong style="color:var(--text-primary); font-size:0.88rem; display:block;">Want to work with this creator?</strong>
                <span style="font-size:0.75rem; color:var(--text-muted);">Simulate commissioning ${currentModel.creator} with this prompt.</span>
              </div>
              <button class="btn btn-emerald btn-sm" onclick="PromptPlayground.commissionCreator()">
                Simulate Direct Commission (Demo)
              </button>
            </div>
          </div>
        </div>
      </div>
    `;
  },

  selectModel(modelId) {
    this.currentModelId = modelId;
    this.render();
  },

  injectTag(tag) {
    const input = document.getElementById('playgroundPromptInput');
    if (input) {
      input.value = `${input.value.trim()}, ${tag}`;
      App.showToast(`Injected style token: "${tag}"`, 'info');
    }
  },

  runSimulation() {
    if (this.isGenerating) return;
    this.isGenerating = true;

    const overlay = document.getElementById('simProgressOverlay');
    const bar = document.getElementById('simProgressBar');
    const stepLabel = document.getElementById('simStepLabel');
    const denoiseLabel = document.getElementById('simDenoiseLabel');
    const renderImg = document.getElementById('simRenderImg');
    const runBtn = document.getElementById('runSimulationBtn');

    if (!overlay || !bar || !runBtn) {
      this.isGenerating = false;
      return;
    }

    overlay.style.display = 'flex';
    runBtn.disabled = true;
    runBtn.style.opacity = '0.6';

    if (renderImg) {
      renderImg.style.filter = 'blur(16px) contrast(150%)';
    }

    const selectedSteps = Number(document.getElementById('samplerStepsInput')?.value) || 32;
    const selectedCfg = Number(document.getElementById('cfgScaleInput')?.value) || 4.5;
    const previewStatus = document.getElementById('simPreviewStatus');
    if (previewStatus) previewStatus.textContent = 'Running local demo animation. No image is being generated.';

    let progress = 0;
    const interval = setInterval(() => {
      progress += 5;
      const step = Math.round((progress / 100) * selectedSteps);

      bar.style.width = `${progress}%`;
      if (stepLabel) stepLabel.innerText = `Demo step ${step}/${selectedSteps}`;
      if (denoiseLabel) denoiseLabel.innerText = `Animation progress: ${progress}% (CFG ${selectedCfg})`;

      if (progress >= 100) {
        clearInterval(interval);
        setTimeout(() => {
          overlay.style.display = 'none';
          if (renderImg) {
            renderImg.style.filter = 'none';
          }
          runBtn.disabled = false;
          runBtn.style.opacity = '1';
          this.isGenerating = false;
          if (previewStatus) previewStatus.textContent = 'Demo animation complete. The sample image is unchanged.';
          App.showToast('Demo animation complete. The sample image was not changed.', 'success');
        }, 300);
      }
    }, 55);
  },

  commissionCreator() {
    const currentModel = CREOVATE_DATA.simulatorModels.find(m => m.id === this.currentModelId) || CREOVATE_DATA.simulatorModels[0];
    const creator = CREOVATE_DATA.creators.find(c => c.creatorName === currentModel.creator || c.name.includes(currentModel.creator.split(' ')[0])) || CREOVATE_DATA.creators[0];

    App.openInviteModal(creator.id);
  }
};
